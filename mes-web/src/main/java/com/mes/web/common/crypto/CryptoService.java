package com.mes.web.common.crypto;

/**
 * 목적: 암호화/복호화 기능을 표준화한다.
 * 기능: 암복호/해시 기능을 제공하는 인터페이스를 정의한다.
 * 이유: 상용화 시 KCMVP 모듈로 교체 가능하도록 경계를 고정하기 위함이다.
 * 유지보수: 구현체 교체 시 이 인터페이스를 유지한다.
 */
public interface CryptoService {

    /**
     * 목적: 평문을 암호문 컨테이너로 변환한다.
     * 기능: 컨테이너(JSON) 포맷으로 암호문을 생성한다.
     * 이유: 암호 경계를 고정하고 포맷을 유지하기 위함이다.
     * 유지보수: 포맷 변경 금지 원칙을 준수한다.
     */
    String encrypt(String plaintext, String aad);

    /**
     * 목적: 암호문 컨테이너를 평문으로 복호화한다.
     * 기능: 컨테이너의 필드를 파싱해 복호화한다.
     * 이유: 상용 모듈 전환 시에도 동일 포맷을 유지하기 위함이다.
     * 유지보수: 복호 정책 변경 시 구현체만 수정한다.
     */
    String decrypt(String container);

    /**
     * 목적: 입력값의 무결성 해시를 생성한다.
     * 기능: SHA-256 해시를 Base64로 반환한다.
     * 이유: 로그/무결성 검증에 사용하기 위함이다.
     * 유지보수: 알고리즘 교체 시 구현체를 수정한다.
     */
    String hash(String input);
}

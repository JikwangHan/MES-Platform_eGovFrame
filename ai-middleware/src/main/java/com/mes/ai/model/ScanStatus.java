package com.mes.ai.model;

/**
 * 보안 스캔 결과 상태를 정의합니다.
 * 목적: 스캔 결과를 표준 값으로 관리해 후속 처리 분기를 단순화합니다.
 * 이유: 문자열 하드코딩을 줄여 일관된 정책 적용을 보장합니다.
 */
public enum ScanStatus {
    /** 악성코드가 발견되지 않은 상태입니다. */
    CLEAN,
    /** 악성코드 또는 의심 시그니처가 발견된 상태입니다. */
    INFECTED,
    /** 스캔 오류로 결과를 확정할 수 없는 상태입니다. */
    ERROR,
    /** 제한 시간 초과로 스캔이 종료된 상태입니다. */
    TIMEOUT
}

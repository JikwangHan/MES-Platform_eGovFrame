package com.mes.ai.crypto;

/**
 * 암호화 서비스 인터페이스입니다.
 * 목적: CryptoService 경계를 고정하여 암호모듈 교체를 쉽게 합니다.
 * 기능: 문자열 데이터를 암호문 컨테이너 포맷으로 변환합니다.
 * 이유: 개발/상용화 단계에서 구현체만 교체하기 위함입니다.
 * 유지보수: 암호 정책 변경 시 구현체를 교체하고 인터페이스는 유지합니다.
 */
public interface CryptoService {
    /**
     * 목적: 입력 문자열을 암호문 컨테이너로 변환합니다.
     * 기능: AEAD 기반 암호화를 수행하고 컨테이너 문자열을 반환합니다.
     * 이유: 저장/전송 단계에서 암호문 포맷을 일관되게 유지하기 위함입니다.
     * 유지보수: AAD/포맷 규칙 변경 시 구현체를 수정합니다.
     */
    String encrypt(String plainText, String aad);

    /**
     * 목적: 암호화 기능이 실제로 동작하는지 여부를 반환합니다.
     * 기능: 활성화 여부를 boolean으로 제공합니다.
     * 이유: 운영 점검 및 로직 분기 판단에 사용합니다.
     * 유지보수: 정책 변경 시 구현체에서 값을 조정합니다.
     */
    boolean isEnabled();
}

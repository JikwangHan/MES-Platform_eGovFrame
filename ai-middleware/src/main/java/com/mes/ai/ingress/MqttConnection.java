package com.mes.ai.ingress;

/**
 * MQTT 연결 인터페이스입니다.
 * 목적: 실제 MQTT 라이브러리 의존성을 숨깁니다.
 * 기능: 연결/구독/해제를 표준 메서드로 제공합니다.
 * 이유: 구현 교체가 쉬운 구조를 만들기 위함입니다.
 * 유지보수: 다른 MQTT 라이브러리를 도입할 때 구현체만 교체합니다.
 */
public interface MqttConnection {
    /**
     * 브로커에 연결합니다.
     * 목적: 수신 준비를 완료합니다.
     * 기능: 연결 상태를 활성화합니다.
     * 이유: 구독/수신 처리를 가능하게 하기 위함입니다.
     * 유지보수: 연결 정책 변경 시 구현체에서 처리합니다.
     */
    void connect();

    /**
     * 토픽을 구독하고 메시지 수신 콜백을 설정합니다.
     * 목적: 수신 데이터를 처리기로 전달합니다.
     * 기능: 구독 대상과 콜백을 연결합니다.
     * 이유: 수신 데이터를 파이프라인으로 전달하기 위함입니다.
     * 유지보수: QoS/구독 옵션 확장은 구현체에 추가합니다.
     */
    void subscribe(MqttMessageHandler handler);

    /**
     * 연결을 종료합니다.
     * 목적: 리소스를 정리합니다.
     * 기능: 연결을 해제하고 내부 상태를 정리합니다.
     * 이유: 종료 시 리소스 누수를 방지하기 위함입니다.
     * 유지보수: 정상 종료 로직 추가 시 구현체에서 보강합니다.
     */
    void disconnect();
}
